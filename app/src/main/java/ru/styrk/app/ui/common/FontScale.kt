package ru.styrk.app.ui.common

import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.ui.platform.LocalDensity
import androidx.compose.ui.unit.Density

/**
 * Потолок для увеличения шрифта — только для несущей обвязки экрана.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО
 *
 * Android умеет увеличивать шрифт во всех приложениях сразу, вплоть
 * до двукратного. Люди включают это не от скуки: кому-то без этого
 * дневник просто не прочитать.
 *
 * Обычный текст от такого увеличения не страдает — строка становится
 * длиннее, экран прокручивается дальше, и всё. Но есть места, где
 * высота задана намертво: нижняя панель, полоса вкладок, плашка
 * со счётчиками. Там подпись, ставшая вдвое длиннее, переносится
 * на вторую строку и ломает разметку — «Профиль» превращается
 * в «Проф / иль».
 *
 * ПОЧЕМУ НЕ ОБРЕЗАТЬ МАСШТАБ ЦЕЛИКОМ
 *
 * Соблазн есть: одна строка в теме — и никаких хлопот. Но это значит
 * отобрать у человека настройку, которую он включил осознанно и,
 * возможно, по необходимости. Приложение, которое молча игнорирует
 * системную доступность, — плохое приложение, как бы ровно оно
 * ни выглядело.
 *
 * Поэтому потолок ставится ТОЧЕЧНО и только там, где увеличивать
 * дальше некуда физически. Содержимое — тренировки, веса, рекорды,
 * советы — масштабируется полностью, без всяких ограничений.
 *
 * КАК ЭТО РАБОТАЕТ
 *
 * Подменяется плотность экрана: физический размер точки остаётся
 * прежним, меняется только множитель шрифта. Значит кнопки, отступы
 * и иконки внутри не сдвигаются ни на волос — двигается только текст.
 *
 * Если человек шрифт не увеличивал (или увеличил слабее потолка),
 * не подменяется ничего: лишний слой в дереве там ни к чему.
 */
@Composable
fun CappedFontScale(max: Float, content: @Composable () -> Unit) {
    val current = LocalDensity.current
    if (current.fontScale <= max) {
        content()
        return
    }
    CompositionLocalProvider(
        LocalDensity provides Density(density = current.density, fontScale = max)
    ) { content() }
}

/**
 * Потолок для несущей обвязки. Один на всё приложение.
 *
 * 1,1 — то есть подписи могут вырасти лишь на десятую часть. Немного,
 * и это не скромность, а арифметика: считано по самому узкому экрану,
 * на котором приложение запускается, — 320 точек.
 *
 * Такой экран получается не только у старых аппаратов. Его получает
 * и тот, кто на обычном телефоне увеличил не шрифт, а масштаб
 * изображения целиком, — а это ровно те же люди, ради которых
 * всё и делается.
 *
 * Считалось по СУММЕ подписей, а не по каждой отдельно: ширина вкладки
 * зависит от её текста, и короткие подписи отдают место длинным.
 * Мерить надо весь ряд.
 *
 * Расчёт лежит в проверке_шрифта.py и повторяется одной командой.
 * Появится подпись длиннее нынешних — проверка провалится и назовёт,
 * какая именно. Это важнее самого числа: число ещё изменится,
 * а способ его получить останется.
 */
const val CHROME_FONT_CAP = 1.1f

/**
 * Плотные ряды с числами: карточки рекордов, шапка архива, шапка идущей
 * тренировки.
 *
 * Потолок выше, чем у обвязки, — 1,25 против 1,1. Здесь есть куда расти:
 * это отдельные карточки, а не полоса высотой в сорок точек.
 *
 * Но потолок нужен и здесь, и вот почему. В таком ряду соседствуют
 * большое число, подпись, дата и вес. Когда числу становится тесно,
 * Compose не обрезает его и не уменьшает — он переносит ПО БУКВАМ,
 * ставя их столбиком: «1», «0», «0», «0». Читать это невозможно,
 * и на ошибку не похоже — похоже на поломку.
 *
 * Одного потолка мало: рядом с ним у каждой такой надписи стоит запрет
 * переноса. Потолок делает, чтобы обычно всё помещалось; запрет —
 * чтобы в необычном случае надпись обрезалась с краю, а не рассыпалась
 * в столбик.
 */
const val DATA_FONT_CAP = 1.25f

/**
 * Общий потолок на всё приложение. Последняя линия обороны.
 *
 * ПОЧЕМУ ОН ВСЁ-ТАКИ ПОЯВИЛСЯ
 *
 * Сначала я ставил потолки точечно и был против общего: увеличенный
 * шрифт человек включил осознанно, и отменять его настройку нехорошо.
 *
 * Но за несколько заходов выяснилось, что плотных мест в приложении
 * много: пояснения под календарём, карточки рекордов, шапка архива,
 * шапка идущей тренировки, свод по завершённой тренировке. Каждое
 * находилось по новому снимку, и каждый раз это была одна и та же
 * поломка — буквы столбиком.
 *
 * Чинить их по одному значит чинить бесконечно и всё равно
 * пропускать. Поэтому здесь стоит общий потолок, а точечные потолки
 * остаются поверх него для мест, где и его много.
 *
 * ЧТО ЭТО ЗНАЧИТ ДЛЯ ЧЕЛОВЕКА
 *
 * До полуторного увеличения приложение слушается настройки полностью.
 * Дальше — перестаёт. Это честный размен: полуторный шрифт читается,
 * а двукратный превращал экраны в мешанину, где не читалось ничего.
 *
 * Кому и полутора мало, тому помогает системное увеличение экрана
 * целиком — оно работает поверх любого приложения и его мы не трогаем.
 *
 * Число одно, менять его здесь.
 */
const val APP_FONT_CAP = 1.5f
