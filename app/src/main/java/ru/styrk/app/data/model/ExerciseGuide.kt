         * в assets: иначе на месте гифки оставалось пустое место, а понять,
         * что дело в отсутствующем или иначе названном файле, было нельзя.
         */
        val hasGif: Boolean get() = gifAsset.isNotBlank() && hasAsset(gifAsset)
    }

    // ── список файлов, реально лежащих в assets/gifs ─────────────────
    // Заполняется один раз при старте приложения (StyrkApp).
    //
    // Ключ — имя БЕЗ расширения и в нижнем регистре. Так сделано по двум
    // причинам, и обе уже кусались:
    //
    //  1. Android различает регистр в именах файлов. "Airbike.gif"
    //     и "airbike.gif" для него два разных файла — из-за этого одна
    //     гифка однажды не показывалась вовсе.
    //
    //  2. Расширение может смениться. Ролики переведены из GIF в WebP,
    //     и если бы ключом было полное имя, пришлось бы править все
    //     записи справочника вручную. Теперь достаточно положить
    //     рядом файл с тем же именем и другим расширением — справочник
    //     найдёт его сам. Формат при этом можно менять и дальше.
    @Volatile
    private var assetIndex: Map<String, String>? = null

    /** Имя без расширения, в нижнем регистре: "Airbike.gif" → "airbike". */
    private fun key(file: String): String = file.substringBeforeLast('.').lowercase()

    fun indexAssets(fileNames: Array<String>?) {
        // Если вдруг рядом окажутся и gif, и webp с одним именем, побеждает
        // тот, что новее по формату: webp меньше и рисуется быстрее.
        val map = HashMap<String, String>()
        fileNames.orEmpty().sortedBy { if (it.endsWith(".webp", true)) 1 else 0 }
            .forEach { map[key(it)] = it }
        assetIndex = map
    }

    /**
     * Есть ли такой файл. Пока список не построен (например, в предпросмотре
     * Compose) отвечаем «да» — иначе гифки не показывались бы вообще.
     */
    fun hasAsset(file: String): Boolean {
        val idx = assetIndex ?: return true
        return idx.containsKey(key(file))
    }

    fun assetUri(file: String): String {
        // Подставляем имя файла ровно в том написании, в котором он лежит
        // на диске: другой регистр и другое расширение здесь допустимы.
        val actual = assetIndex?.get(key(file)) ?: file
        return "file:///android_asset/gifs/$actual"
    }

