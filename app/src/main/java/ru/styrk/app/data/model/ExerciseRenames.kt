/**
 * ПЕРЕИМЕНОВАНИЯ СПРАВОЧНИКА — один раз и навсегда.
 *
 * Название упражнения в дневнике — не подпись, а опознавательный знак.
 * По нему связаны история подходов, рекорды, планы, цели, шаблоны
 * и разбор техники. Поправить название в справочнике и забыть про
 * записи — значит оставить человеку рекорд, висящий на имени, которого
 * больше нет, и новое упражнение с пустой историей. Два упражнения
 * вместо одного, и виноват дневник.
 *
 * Поэтому правка названий всегда идёт парой: новое имя в справочнике
 * И перенос всех записей на него. Перенос делает миграция базы
 * (MIGRATION_6_7) — один раз, при первом запуске новой версии,
 * целиком внутри одной транзакции: либо всё, либо ничего.
 *
 * Что здесь лежит:
 *   1) потерянная «ё» — «Подъем» вместо «Подъём». В приложении везде
 *      «тренажёре», «лёжа», «звёздочка», а в «подъёме» ё потерялась;
 *   2) «Пуловер с гантелей» — ошибка падежа, нужен творительный:
 *      «с гантелью», как в соседнем «Кикбэк с гантелью»;
 *   3) разнобой в одинаковых семьях: сначала движение, потом снаряд,
 *      потом уточнение. Так список читается сверху вниз, а не
 *      разгадывается.
 *
 * ОДНО СВЕДЕНИЕ. «Жим гантелей на наклонной вверх (верх груди)»
 * и «Жим гантелей на наклонной скамье» — одно и то же движение под
 * двумя именами. Теперь это «Жим гантелей на наклонной скамье вверх».
 * У кого в истории есть оба, записи сольются в одно упражнение,
 * а рекорд останется тот, который выше.
 *
 * Эти же правила применяет дневник в браузере и сервер — иначе имена
 * разъехались бы при первом же обмене.
 */
