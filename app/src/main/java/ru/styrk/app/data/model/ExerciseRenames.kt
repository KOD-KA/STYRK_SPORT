     * стало бы две истории.
     *
     * Замена идёт вместе с кавычками — меняется ровно целое название,
     * а не кусок соседнего. Так же приводит имена сервер.
     */
    fun applyToJson(json: String): String {
        var out = json
        for ((old, new) in ALL) {
            val q = "\"" + old + "\""
            if (out.contains(q)) out = out.replace(q, "\"" + new + "\"")
        }
        return out
    }
