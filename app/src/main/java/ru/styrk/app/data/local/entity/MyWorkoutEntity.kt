package ru.styrk.app.data.local.entity

import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * Своя тренировка — образец, а не событие.
 *
 * Разница с журналом принципиальная. В журнале лежит то, что было:
 * дата, вес снаряда, число повторов. Здесь — то, что человек собирается
 * повторять: название, группы мышц и набор упражнений. Ни дат,
 * ни результатов.
 *
 * Зачем это нужно. Тот, кто ходит по своей программе, делает один
 * и тот же набор из недели в неделю. Набирать его заново каждый раз —
 * работа на пустом месте, а готовые подборки в «Инфо» чужие
 * и подходят не всем.
 *
 * Такие образцы уже есть в браузерной версии и в мини-приложении
 * Telegram. Здесь они появляются последними, и вид обмена берётся
 * тот же самый — my_workout, — иначе одно и то же на трёх устройствах
 * называлось бы по-разному и не сходилось.
 */
@Entity(tableName = "my_workouts")
data class MyWorkoutEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,

    /** Название, которое дал человек: «Грудь · понедельник». */
    val title: String,

    /**
     * Группы мышц одной строкой, как их видит человек: «Грудь, Трицепс».
     *
     * Здесь СОЗНАТЕЛЬНО не имя перечисления, в отличие от своих
     * упражнений. Групп в образце может быть несколько, а перечисление
     * хранит ровно одну; хранить список ключей значило бы завести
     * ещё одну таблицу ради строки, которую всё равно показывают
     * целиком. Браузерная версия хранит это поле так же.
     */
    val muscleGroup: String,

    // ═══ ПОЛЯ ДЛЯ СИНХРОНИЗАЦИИ ═══
    // Те же три, что у остальных записей: постоянный опознавательный
    // знак, время последнего изменения и отметка «ещё не отправлено».
    val uuid: String = java.util.UUID.randomUUID().toString(),
    val updatedAt: Long = System.currentTimeMillis(),
    val dirty: Int = 1
)