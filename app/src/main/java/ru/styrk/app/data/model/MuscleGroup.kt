package ru.styrk.app.data.model

/**
 * Блоки (группы) на экране выбора упражнений.
 *
 * v1.8.3: «Улица» и «Дом» ОБЪЕДИНЕНЫ в один блок «Улица и дом».
 * Упражнения там по сути одинаковые (свой вес, без тренажёров),
 * а блоков стало ровно 12.
 *
 * ВАЖНО: имена констант (CHEST, STREET, HOME…) хранятся в базе как строки.
 * Удалять или переименовывать их НЕЛЬЗЯ — старые записи перестанут
 * находиться. Поэтому HOME остался в списке, но помечен скрытым:
 * при выборе он больше не показывается, а старая история продолжает
 * читаться и приравнивается к STREET (см. [sameAs]).
 */
enum class MuscleGroup(
    val title: String,
    /** false = блок не показывается при выборе, нужен только старым записям */
    val selectable: Boolean = true
) {
    CHEST("Грудь"),
    BACK("Спина"),
    LEGS("Ноги"),
    SHOULDERS("Плечи"),
    BICEPS("Бицепс"),
    TRICEPS("Трицепс"),
    ABS("Пресс"),
    FOREARMS("Предплечья"),
    NECK("Шея"),
    STRETCH("Растяжка"),

    // ДОБАВЛЕНО (этап «новые группы»). Имена констант хранятся в БД —
    // не переименовывать. Новые группы добавлены в конец, чтобы
    // привычный порядок на экране выбора не поменялся.
    STREET("Улица и дом"),
    HOME("Дом", selectable = false),   // слит с STREET в v1.8.3
    FAT_BURN("Жиросжигание");

    /** Блок, в котором упражнение показывается СЕЙЧАС (HOME слился с STREET). */
    val merged: MuscleGroup
        get() = if (this == HOME) STREET else this

    /** Сравнение групп с учётом слияния «Дом» → «Улица и дом». */
    fun sameAs(other: MuscleGroup?): Boolean =
        other != null && other.merged == this.merged

    companion object {
        /** Список для экранов выбора — без скрытых блоков (сейчас 12 штук). */
        val visible: List<MuscleGroup>
            get() = entries.filter { it.selectable }
    }
}