package ru.styrk.app.data.model

/**
 * Содержимое вкладки «Инфо»: советы, программы на неделю и тренировки легенд.
 *
 * Раньше всё это лежало внутри экрана, закрытыми списками. Переехало сюда,
 * чтобы веб-дневник собирал свою копию из этого же файла
 * (tools/собрать_инфо.py) — два набора текстов на две платформы однажды
 * разошлись бы.
 *
 * Все упражнения в программах и легендах взяты из справочника: день
 * можно запланировать или начать, и он подставится целиком.
 */
data class TrainingTip(val icon: String, val title: String, val body: String)

data class ProgramDay(val label: String, val muscleGroup: String, val exercises: List<String>)

data class TrainingProgram(
    val title: String,
    val subtitle: String,
    /** Как проходить программу: частота, подходы, прибавка. */
    val guide: List<String>,
    val days: List<ProgramDay>
)

data class Legend(
    val emoji: String,
    val name: String,
    val tagline: String,
    val description: String,
    /** Как тренировался — строки как есть, с подходами и пояснениями. */
    val workout: List<String>,
    /** Для «попробовать повторить»: группа-ярлык и чистые названия из справочника. */
    val muscleGroup: String,
    val plannableExercises: List<String>,
    /**
     * Цитата — только та, что действительно звучала и известна.
     * Нет такой — нет и цитаты: приписать человеку слова, которых он
     * не говорил, хуже, чем оставить карточку без них.
     */
    val quote: String? = null,
    val quoteSource: String? = null
)

