package ru.styrk.app.data.model

/**
 * ДВЕ ГАНТЕЛИ — ДВОЙНОЙ ОБЪЁМ.
 *
 * В поле веса человек пишет вес ОДНОЙ гантели: так написано на самой
 * гантели, так их называют в зале и так считают рекорд («жму
 * тридцатку»). Но поднимает он при этом две.
 *
 * Объём — это сколько килограммов человек поднял. Жим гантелей
 * 30 × 10 — не 300 кг, а 600: тридцать в каждой руке. Раньше считалось
 * по первому, и все гантельные упражнения были занижены ровно вдвое.
 *
 * Здесь перечислены упражнения, где снарядов ДВА и поднимаются они
 * ОДНОВРЕМЕННО. Список сверен со всем справочником — и с описанием
 * техники каждого упражнения, а не только с названием.
 *
 * Не вошли: односторонние (тяга гантели одной рукой, кикбэк,
 * концентрированный подъём, скамья Скотта одной рукой, разгибание
 * из-за головы, боковые наклоны) — снаряд один, подход на каждую руку;
 * поочерёдные («молот через корпус», «подъём поочерёдно с супинацией»)
 * — в описании техники сказано, что руки чередуются, значит в каждом
 * повторе поднимается одна гантель; одна гантель в двух руках (пуловер,
 * приседания с гантелью у груди, подъём блина перед собой).
 *
 * Жим Арнольда, разводка на наклонной скамье и сгибания Зоттмана
 * в списке есть, хотя слова «гантели» в названии нет: это гантельные
 * упражнения по сути и делаются двумя руками сразу.
 *
 * ВАЖНО: список обязан совпадать слово в слово с тем, что в дневнике
 * (PAIRED в app.html) и на сервере (PAIRED в server.js). Разойдутся —
 * и человек увидит разный объём за одну неделю в трёх местах, а какой
 * из них правильный, не поймёт никто.
 *
 * Рекорд по весу от этого не меняется: тридцатка остаётся тридцаткой.
 * Меняется только объём — и в прошлых тренировках тоже, потому что
 * он нигде не хранится, а считается заново из подходов.
 */
object PairedExercises {

    private val NAMES = setOf(
        // грудь
        "Жим гантелей лёжа",
        "Жим гантелей лёжа на полу",
        "Жим гантелей на наклонной скамье вверх",
        "Жим гантелей на наклонной скамье вниз",
        "Жим гантелей на наклонной скамье нейтральным хватом",
        "Разводка гантелей лёжа",
        "Разводка на наклонной скамье",
        // спина и трапеция
        "Тяга двух гантелей в наклоне",
        "Шраги с гантелями",
        "Шраги с гантелями (трапеция)",
        // ноги
        "Выпады с гантелями",
        "Обратные выпады с гантелями",
        // плечи
        "Жим гантелей стоя",
        "Жим гантелей сидя",
        "Жим гантелей нейтральным хватом сидя",
        "Жим Арнольда",
        "Подъём гантелей перед собой",
        "Разводка гантелей в стороны",
        "Махи гантелями в стороны сидя",
        "Махи гантелями в наклоне",
        "Разводка гантелей лёжа лицом вниз",
        "Протяжка с гантелями",
        // бицепс
        "Подъём гантелей на бицепс",
        "Подъём гантелей сидя на наклонной",
        "Молотки с гантелями",
        "Сгибания Зоттмана сидя",
        // трицепс
        "Французский жим с гантелями",
        // предплечья
        "Сгибание запястий с гантелями",
        "Разгибание запястий с гантелями",
        /* кроссовер: две стойки, на каждой свой вес

           Здесь та же история, что с гантелями, только снаряд другой.
           В разводке и сведении в кроссовере тянут две руки от двух
           стоек, и на пине каждой стоит свой вес. Человек записывает
           то, что видит на пине, — вес ОДНОЙ стороны, — а поднимает
           обе. Значит объём вдвое больше.

           Односторонние блочные упражнения сюда не входят: там стойка
           одна («Махи в стороны на блоке», «Тяга блока одной рукой»,
           «Разгибание на трицепс одной рукой в блоке» и прочие
           с «одной рукой» в названии). */
        "Сведение в кроссовере снизу вверх",
        "Сведение в кроссовере сверху вниз",
        "Сведение рук в кроссовере лёжа на скамье",
        "Разводка в кроссовере",
        "Разводка в кроссовере на заднюю дельту",
        "Сгибания рук в кроссовере (двойной бицепс)"
    )

    /** Сколько снарядов в руках: два или один. */
    fun arms(exerciseName: String?): Int =
        if (exerciseName != null && NAMES.contains(exerciseName)) 2 else 1

    /** Две гантели или один снаряд — для подписей в интерфейсе. */
    fun isPaired(exerciseName: String?): Boolean = arms(exerciseName) == 2

    /** Объём одного подхода в килограммах. */
    fun volume(weight: Float, reps: Int, exerciseName: String?): Double =
        weight.toDouble() * reps * arms(exerciseName)
}
