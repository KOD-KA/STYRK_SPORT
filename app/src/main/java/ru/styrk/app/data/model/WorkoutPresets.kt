/**
 * Готовые подборки упражнений - по пять на каждый блок.
 *
 * Это не чужие авторские программы: копировать методику из книги
 * и подписывать своим именем нельзя. Здесь общепризнанные принципы,
 * которым учат везде и которые ничьей собственностью не являются:
 *
 *   - тяжёлое базовое движение идёт первым, пока есть силы;
 *   - на массу 8-12 повторов, на силу 5 и меньше с длинным отдыхом,
 *     на рельеф 12-15 с коротким;
 *   - изоляция после базы, а не вместо неё;
 *   - у каждого блока есть вариант без железа, дома или на улице.
 *
 * Все упражнения взяты из справочника приложения: подборку можно
 * запланировать или начать, и она подставится целиком.
 */
data class WorkoutPreset(
    /** Ради чего эта подборка: «Масса», «Сила», «Дома, без железа». */
    val title: String,
    /** Одна строка пояснения - что здесь особенного. */
    val note: String,
    /** Подходы и повторы одной строкой: «3-4 подхода x 8-12». */
    val volume: String,
    val exercises: List<String>,
    /**
     * Как выполнять эту тренировку: отдых, вес, порядок, прибавка.
     * Показывается в «Подробнее» вместе с роликами упражнений.
     */
    val guide: List<String> = emptyList()
)

